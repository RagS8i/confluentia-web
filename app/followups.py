"""Adaptive, persistent follow-up questions and answers.

Questions are generated by deterministic gap checks, approved by staff, sent
through the outbox, and answered in the secure patient channel. An answer is
stored as a new typed source and the case is reprocessed so new information can
add warnings or update the existing evidence trail. Prior warnings are never
deleted.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from STT_translation.languages import (
    FOLLOWUP_LANGUAGE_CODES,
    normalize_bcp47,
    short_code,
)

from .config import Settings
from .db import Database
from .outbound import DeliveryError, deliver
from .pipeline.normalize import InputError, adapt_stt, adapt_typed
from .schemas import (
    CaseRecord,
    CaseStatus,
    ClinicalSummary,
    FollowUpAnswer,
    FollowUpRecord,
    FollowUpStatus,
    Outcome,
)
from .storage import Cipher, random_id, safe_error, sha256_text

# Compact CareFlow codes accepted for follow-up authoring/localization.  This
# covers the 11 voice-capable languages plus Hinglish.  Translations are
# generated on demand rather than pre-approving every variant.
SUPPORTED_FOLLOWUP_LANGUAGES = set(FOLLOWUP_LANGUAGE_CODES)


def normalize_followup_language(value: Optional[str], default: str = "en") -> str:
    """Return a compact follow-up language code or raise ``FollowUpError``."""
    if value is None or not str(value).strip():
        return default
    raw = str(value).strip().lower().replace("_", "-")
    if raw == "hinglish":
        return "hinglish"
    normalized = short_code(raw)
    if normalized is None or normalized not in SUPPORTED_FOLLOWUP_LANGUAGES:
        raise FollowUpError(
            "unsupported_language",
            "This language is not supported for patient follow-up.",
        )
    return normalized


class FollowUpError(RuntimeError):
    def __init__(self, code: str, message: str, status_code: int = 422):
        super().__init__(message)
        self.code = code
        self.message = message
        self.status_code = status_code


class FollowUpService:
    def __init__(
        self,
        settings: Settings,
        db: Database,
        cipher: Cipher,
        pipeline=None,
    ):
        self.settings = settings
        self.db = db
        self.cipher = cipher
        self.pipeline = pipeline

    def sync_from_summary(
        self, case: CaseRecord, summary: Optional[ClinicalSummary], actor: str = "system"
    ) -> List[FollowUpRecord]:
        if summary is None or case.workflow_status == Outcome.emergency:
            return []
        created: List[FollowUpRecord] = []
        for question in summary.follow_up_questions:
            existing = self.db.get_followup_by_question(
                case.case_id, question.question_id, self.cipher
            )
            if existing is not None:
                created.append(existing)
                continue
            language = "en"
            if question.language:
                try:
                    language = normalize_followup_language(question.language)
                except FollowUpError:
                    language = "en"
            record = FollowUpRecord(
                followup_id="fu_" + sha256_text(case.case_id + question.question_id)[:20],
                case_id=case.case_id,
                question_id=question.question_id,
                text=question.text,
                language=language,
                addresses=list(question.addresses),
                rationale=question.rationale,
                origin="deterministic_gap_check",
                created_by=actor,
                metadata={"workflow_status": case.workflow_status.value},
            )
            self.db.save_followup(record, self.cipher)
            created.append(record)
        if created:
            self.db.audit(
                actor,
                "system",
                "followup_questions_synced",
                case.case_id,
                {"count": len(created)},
            )
        return created

    def list_for_case(self, case_id: str) -> List[FollowUpRecord]:
        return self.db.get_followups(case_id, self.cipher)

    def answers_for_case(self, case_id: str) -> List[FollowUpAnswer]:
        return self.db.get_followup_answers(case_id, self.cipher)

    def _get(self, case_id: str, followup_id: str) -> FollowUpRecord:
        record = self.db.get_followup(case_id, followup_id, self.cipher)
        if record is None:
            raise FollowUpError("not_found", "Follow-up question not found.", 404)
        return record

    def approve(
        self,
        case_id: str,
        followup_id: str,
        actor: str,
        role: str,
        text: Optional[str] = None,
        language: Optional[str] = None,
    ) -> FollowUpRecord:
        record = self._get(case_id, followup_id)
        if record.status not in {FollowUpStatus.suggested}:
            raise FollowUpError(
                "invalid_status", f"Follow-up cannot be approved from {record.status.value}."
            )
        if text is not None:
            if not text.strip():
                raise FollowUpError("empty_question", "Follow-up text is empty.")
            record.text = text.strip()
            record.metadata["staff_edited"] = True
        if language is not None:
            record.language = normalize_followup_language(language)
            record.metadata["localized_language"] = normalize_bcp47(language)
        record.status = FollowUpStatus.approved
        record.approved_by = actor
        record.approved_at = datetime.now(timezone.utc)
        self.db.save_followup(record, self.cipher)
        self.db.audit(
            actor,
            role,
            "followup_approved",
            case_id,
            {"followup_id": followup_id, "edited": bool(text), "language": record.language},
        )
        return record

    def send(self, case_id: str, followup_id: str, actor: str, role: str) -> FollowUpRecord:
        record = self._get(case_id, followup_id)
        if record.status != FollowUpStatus.approved:
            raise FollowUpError(
                "approval_required",
                "Only an approved follow-up question can be sent.",
                409,
            )
        case = self.db.get_case(case_id, include_deleted=True)
        if case is None or case.deleted_at or case.consent_withdrawn_at:
            raise FollowUpError("case_unavailable", "Case is not available.", 409)
        record.attempts += 1
        try:
            record.delivery = deliver(
                self.settings,
                self.settings.communication_delivery,
                {
                    "type": "followup_question",
                    "followup_id": record.followup_id,
                    "case_id": record.case_id,
                    "question_id": record.question_id,
                    "language": record.language,
                    "text": record.text,
                },
            )
            record.status = FollowUpStatus.sent
            record.sent_at = datetime.now(timezone.utc)
            record.last_error = None
        except DeliveryError as exc:
            record.status = FollowUpStatus.approved
            record.last_error = safe_error(exc)
        self.db.save_followup(record, self.cipher)
        self.db.audit(
            actor,
            role,
            "followup_sent" if record.status == FollowUpStatus.sent else "followup_send_failed",
            case_id,
            {"followup_id": followup_id, "delivery": record.delivery, "attempts": record.attempts},
        )
        return record

    def dismiss(
        self,
        case_id: str,
        followup_id: str,
        actor: str,
        role: str,
        reason: str,
    ) -> FollowUpRecord:
        record = self._get(case_id, followup_id)
        if record.status == FollowUpStatus.answered:
            raise FollowUpError("already_answered", "An answered follow-up cannot be dismissed.")
        record.status = FollowUpStatus.dismissed
        record.dismissed_by = actor
        record.dismissed_at = datetime.now(timezone.utc)
        record.metadata["dismiss_reason"] = reason
        self.db.save_followup(record, self.cipher)
        self.db.audit(
            actor,
            role,
            "followup_dismissed",
            case_id,
            {"followup_id": followup_id, "reason": reason},
        )
        return record

    def ensure_answerable(self, case_id: str, followup_id: str) -> FollowUpRecord:
        """Validate that a follow-up can currently accept a patient answer."""
        record = self._get(case_id, followup_id)
        if record.status != FollowUpStatus.sent:
            raise FollowUpError(
                "question_not_sent",
                "A follow-up question must be sent before an answer is accepted.",
                409,
            )
        case = self.db.get_case(case_id)
        if case is None or case.consent_withdrawn_at:
            raise FollowUpError("case_unavailable", "Case is not available.", 409)
        if case.consent_granted_at is None:
            raise FollowUpError("consent_required", "Explicit consent is required.", 409)
        return record

    def get_followup(self, case_id: str, followup_id: str) -> FollowUpRecord:
        return self._get(case_id, followup_id)

    def _finalize_answer(
        self,
        record: FollowUpRecord,
        case: CaseRecord,
        answer: FollowUpAnswer,
        source_ids: List[str],
        actor: str,
        role: str,
        reprocess: bool,
        *,
        modality: str,
    ) -> Dict[str, Any]:
        self.db.save_followup_answer(answer, self.cipher)
        record.status = FollowUpStatus.answered
        record.answered_at = answer.created_at
        record.metadata["answer_modality"] = modality
        record.metadata["answer_language"] = answer.language
        self.db.save_followup(record, self.cipher)
        if case.status in {CaseStatus.reviewed}:
            case.status = CaseStatus.queued
            self.db.save_case(case)
        self.db.audit(
            actor,
            role,
            "followup_answered",
            record.case_id,
            {
                "followup_id": record.followup_id,
                "answer_id": answer.answer_id,
                "source_ids": source_ids,
                "modality": modality,
                "reprocessed": reprocess,
            },
        )
        processing = "not_requested"
        if reprocess:
            try:
                if self.pipeline is not None:
                    if self.settings.processing_mode == "sync":
                        self.pipeline.process_case(record.case_id, actor=actor)
                        processing = "completed"
                    else:
                        self.pipeline.submit(record.case_id, actor)
                        processing = "queued"
            except Exception as exc:
                processing = f"failed:{type(exc).__name__}"
                self.db.audit(
                    actor,
                    role,
                    "followup_reprocess_failed",
                    record.case_id,
                    {"answer_id": answer.answer_id, "error": safe_error(exc)},
                )
        return {
            "answer": answer,
            "followup": record,
            "processing": processing,
        }

    def answer(
        self,
        case_id: str,
        followup_id: str,
        text: str,
        language: Optional[str],
        actor: str,
        role: str,
        reprocess: bool = True,
    ) -> Dict[str, Any]:
        record = self.ensure_answerable(case_id, followup_id)
        case = self.db.get_case(case_id)
        if not text.strip():
            raise FollowUpError("empty_answer", "Answer text is empty.")
        answer_language = normalize_followup_language(
            language or record.language, default="en"
        )
        answer_id = random_id("ans")
        payload = {
            "text": text.strip(),
            "language": answer_language,
            "message_id": answer_id,
            "captured_at": datetime.now(timezone.utc).isoformat(),
        }
        try:
            sources, _notes = adapt_typed(payload, case_id)
        except InputError as exc:
            raise FollowUpError(exc.code, exc.message) from exc
        source = sources[0]
        source.raw_metadata = {
            **(source.raw_metadata or {}),
            "followup_id": record.followup_id,
            "answer_id": answer_id,
            "answer_modality": "text",
        }
        self.db.upsert_source(source, self.cipher)
        answer = FollowUpAnswer(
            answer_id=answer_id,
            followup_id=record.followup_id,
            case_id=case_id,
            text=text.strip(),
            language=source.language,
            source_id=source.source_id,
            answered_by=actor,
            role=role,
            metadata={"answer_modality": "text"},
        )
        return self._finalize_answer(
            record,
            case,
            answer,
            [source.source_id],
            actor,
            role,
            reprocess,
            modality="text",
        )

    def answer_audio(
        self,
        case_id: str,
        followup_id: str,
        stt_result: Dict[str, Any],
        document_id: str,
        filename: str,
        actor: str,
        role: str,
        reprocess: bool = True,
    ) -> Dict[str, Any]:
        """Persist a voice answer with native and English provenance.

        ``stt_result`` is produced by ``speech_to_language`` with an English
        target.  The native transcript becomes the source and answer text; the
        English translation is retained in source metadata and the encrypted
        answer record.  The stored recording is linked by ``document_id``.
        """
        record = self.ensure_answerable(case_id, followup_id)
        case = self.db.get_case(case_id)
        native = str(stt_result.get("transcription") or "").strip()
        english = str(stt_result.get("translated_text") or "").strip()
        if not native:
            raise FollowUpError(
                "empty_transcription", "No speech was detected in the answer.", 422
            )
        detected = stt_result.get("language_code") or stt_result.get("language")
        chunks = stt_result.get("chunks") or []
        if not isinstance(chunks, list):
            chunks = []
        answer_id = random_id("ans")
        payload = {
            "transcript_id": answer_id,
            "document_id": document_id,
            "file_name": filename,
            "transcription": native,
            "translated_text": english,
            "language": detected,
            "language_code": detected,
            "model": stt_result.get("model"),
            "chunks": chunks,
        }
        try:
            sources, _notes = adapt_stt(payload, case_id)
        except InputError as exc:
            raise FollowUpError(exc.code, exc.message) from exc
        for source in sources:
            source.raw_metadata = {
                **(source.raw_metadata or {}),
                "followup_id": record.followup_id,
                "answer_id": answer_id,
                "answer_modality": "audio",
                "translated_text": english or source.raw_metadata.get("translated_text"),
                "audio_document_id": document_id,
            }
            self.db.upsert_source(source, self.cipher)
        source = sources[0]
        answer = FollowUpAnswer(
            answer_id=answer_id,
            followup_id=record.followup_id,
            case_id=case_id,
            text=native,
            language=source.language,
            source_id=source.source_id,
            answered_by=actor,
            role=role,
            translated_text=english or None,
            document_id=document_id,
            metadata={
                "answer_modality": "audio",
                "detected_language": detected,
                "language_probability": stt_result.get("language_probability"),
                "chunk_count": len(chunks),
            },
        )
        return self._finalize_answer(
            record,
            case,
            answer,
            [item.source_id for item in sources],
            actor,
            role,
            reprocess,
            modality="audio",
        )
