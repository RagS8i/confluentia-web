class CommunicationError(RuntimeError):
    def __init__(self, code: str, message: str, status_code: int = 422):
        super().__init__(message)
        self.code = code
        self.message = message
        self.status_code = status_code


class CommunicationService:
    def __init__(self, settings: Settings, db: Database, cipher: Cipher, queue_ops=None):
        self.settings = settings
        self.db = db
        self.cipher = cipher
        self.queue_ops = queue_ops

    def templates(self, language: Optional[str] = None) -> Dict[str, Any]:
        languages = (
            [language]
            if language and language in SUPPORTED_MESSAGE_LANGUAGES
            else list(SUPPORTED_MESSAGE_LANGUAGES)
        )
        if language and language not in SUPPORTED_MESSAGE_LANGUAGES:
            raise CommunicationError(
                "unsupported_language",
                "No approved communication template exists for this language.",
            )
        return {
            "version": "patient-messages/1.0",
            "languages": languages,
            "templates": [
                {
                    "intent": intent.value,
                    "language": lang,
                    "template_id": f"{intent.value}-{lang}-v1",
                    "curated": True,
                }
                for lang in languages
                for intent in CommunicationIntent
            ],
            "note": (
                "All templates are curated and require staff approval. Missing language variants "
                "are not machine-translated."
            ),
        }

    def draft(
        self,
        case: CaseRecord,
        intent: CommunicationIntent,
        language: str,
        actor: str,
        wait_estimate: Optional[WaitEstimate] = None,
    ) -> PatientMessage:
        if language not in SUPPORTED_MESSAGE_LANGUAGES:
            raise CommunicationError(
                "unsupported_language",
                "No approved communication template exists for this language.",
            )
        if case.consent_withdrawn_at or case.deleted_at:
            raise CommunicationError(
                "case_unavailable", "Communications cannot be drafted for this case.", 409
            )
        if case.workflow_status == Outcome.emergency and intent != CommunicationIntent.urgent_review:
            raise CommunicationError(
                "emergency_requires_urgent_workflow",
                "During emergency escalation, use the urgent review workflow. "
                "Routine status, wait and information-request messages are suppressed.",
                409,
            )
        if intent == CommunicationIntent.urgent_review and case.workflow_status not in {
            Outcome.emergency,
            Outcome.priority_review,
        }:
            raise CommunicationError(
                "urgent_review_not_supported",
                "The case is not currently in an urgent or priority workflow.",
                409,
            )

        texts = _TEXTS[language]
        metadata: Dict[str, Any] = {"workflow_status": case.workflow_status.value}
        if intent == CommunicationIntent.missing_information:
            followups = [
                item
                for item in self.db.get_followups(case.case_id, self.cipher)
                if item.language == language
                and item.status in {FollowUpStatus.suggested, FollowUpStatus.approved}
            ][:3]
            if not followups:
                raise CommunicationError(
                    "no_followup_questions",
                    "No approved-language follow-up questions are available. "
                    "Generate and review follow-up questions first.",
                    409,
                )
            numbered = "\n".join(
                f"{index}. {item.text}" for index, item in enumerate(followups, start=1)
            )
            body = f"{texts['missing_intro']}\n\n{numbered}\n\n{texts['missing_outro']}"
            metadata["followup_ids"] = [item.followup_id for item in followups]
        elif intent == CommunicationIntent.wait_update:
            if wait_estimate is None or not wait_estimate.available:
                raise CommunicationError(
                    "wait_estimate_unavailable",
                    "No defensible wait estimate is available from current operational data.",
                    409,
                )
            body = texts["wait_update"].format(
                minimum=wait_estimate.minimum_minutes,
                maximum=wait_estimate.maximum_minutes,
            )
            metadata["wait_estimate"] = wait_estimate.model_dump(mode="json")
        else:
            body = texts[intent.value]

        message = PatientMessage(
            message_id=random_id("msg"),
            case_id=case.case_id,
            intent=intent,
            language=language,
            template_id=f"{intent.value}-{language}-v1",
            body=body,
            generated_by=actor,
            metadata=metadata,
        )
        self.db.save_communication(message, self.cipher)
        self.db.audit(
            actor,
            "system",
            "communication_drafted",
            case.case_id,
            {
                "message_id": message.message_id,
                "intent": intent.value,
                "language": language,
            },
        )
        return message

    def approve(
        self,
        case_id: str,
        message_id: str,
        actor: str,
        role: str,
        text: Optional[str] = None,
    ) -> PatientMessage:
        message = self.db.get_communication(message_id, self.cipher)
        if message is None or message.case_id != case_id:
            raise CommunicationError("not_found", "Communication not found.", 404)
        if message.status not in {CommunicationStatus.draft, CommunicationStatus.failed}:
            raise CommunicationError(
                "invalid_status", f"Communication cannot be approved from {message.status.value}.", 409
            )
        if text is not None:
            if not text.strip():
                raise CommunicationError("empty_message", "Message text is empty.")
            message.body = text.strip()
            message.metadata["staff_edited"] = True
        message.status = CommunicationStatus.approved
        message.approved_by = actor
        message.approved_at = datetime.now(timezone.utc)
        message.last_error = None
        self.db.save_communication(message, self.cipher)
        self.db.audit(
            actor,
            role,
            "communication_approved",
            case_id,
            {"message_id": message_id, "edited": bool(text)},
        )
        return message

    def send(
        self, case_id: str, message_id: str, actor: str, role: str
    ) -> PatientMessage:
        message = self.db.get_communication(message_id, self.cipher)
        if message is None or message.case_id != case_id:
            raise CommunicationError("not_found", "Communication not found.", 404)
        if message.status != CommunicationStatus.approved:
            raise CommunicationError(
                "approval_required", "Only an approved communication can be sent.", 409
            )
        case = self.db.get_case(case_id, include_deleted=True)
        if case is None or case.deleted_at or case.consent_withdrawn_at:
            raise CommunicationError("case_unavailable", "Case is not available.", 409)
        message.attempts += 1
        try:
            message.delivery = deliver(
                self.settings,
                self.settings.communication_delivery,
                {
                    "type": "patient_message",
                    "message_id": message.message_id,
                    "case_id": message.case_id,
                    "intent": message.intent.value,
                    "language": message.language,
                    "body": message.body,
                },
            )
            message.status = CommunicationStatus.sent
            message.sent_at = datetime.now(timezone.utc)
            message.last_error = None
        except DeliveryError as exc:
            message.status = CommunicationStatus.failed
            message.last_error = safe_error(exc)
        self.db.save_communication(message, self.cipher)
        self.db.audit(
            actor,
            role,
            "communication_sent" if message.status == CommunicationStatus.sent else "communication_failed",
            case_id,
            {
                "message_id": message_id,
                "delivery": message.delivery,
                "attempts": message.attempts,
            },
        )
        return message

    def dismiss(
        self, case_id: str, message_id: str, actor: str, role: str, reason: str
    ) -> PatientMessage:
        message = self.db.get_communication(message_id, self.cipher)
        if message is None or message.case_id != case_id:
            raise CommunicationError("not_found", "Communication not found.", 404)
        if message.status == CommunicationStatus.sent:
            raise CommunicationError("already_sent", "A sent message cannot be dismissed.", 409)
        message.status = CommunicationStatus.dismissed
        message.metadata["dismiss_reason"] = reason
        self.db.save_communication(message, self.cipher)
        self.db.audit(
            actor,
            role,
            "communication_dismissed",
            case_id,
            {"message_id": message_id, "reason": reason},
        )
        return message

    def list_for_case(self, case_id: str) -> List[PatientMessage]:
        return self.db.get_communications(case_id, self.cipher)
